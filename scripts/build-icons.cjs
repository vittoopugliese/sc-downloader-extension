// Offline icon subsetting. The source catalog and build tooling never ship.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

function packageFiles(directory) {
  const script = fs.readFileSync(path.join(directory, 'scripts/package-extension.ps1'), 'utf8');
  const list = script.match(/\$packageItems = @\(([\s\S]*?)\r?\n\s*\)/);
  if (!list) throw new Error('Missing package file list');
  return [...list[1].matchAll(/"([^"]+)"/g)].map(match => match[1]);
}

// Conservative literal analysis covers ternaries, arrays, maps and helper
// arguments. A name shared with ordinary text may be retained unnecessarily.
// Names assembled from fragments or external data must be explicitly included.
function selectNames(sources, aliases, include = []) {
  const used = new Set(['help', ...include]);
  for (const source of sources) {
    for (const match of source.matchAll(/["'\x60]([a-z][a-z0-9:-]*)["'\x60]/gi)) {
      if (Object.hasOwn(aliases, match[1])) used.add(match[1]);
    }
    for (const match of source.matchAll(/<sc-icon\b[^>]*\bname=["']([a-z][a-z0-9:-]*)["']/gi)) {
      if (!Object.hasOwn(aliases, match[1])) throw new Error('Unknown literal icon: ' + match[1]);
    }
  }
  for (const name of used) if (!Object.hasOwn(aliases, name)) throw new Error('Unknown included icon: ' + name);
  return [...used].sort();
}

function compile({ sources, aliases, catalog, runtime, include }) {
  const selected = selectNames(sources, aliases, include);
  const vectors = [], names = {}, indices = new Map();
  for (const name of selected) {
    const svg = catalog[aliases[name]];
    if (!svg || !/^<svg\b/.test(svg) || /<(?:script|image|foreignObject)\b|\bon\w+=|(?:href|url)\s*[=(]/i.test(svg)) {
      throw new Error('Missing or unsafe vector: ' + name);
    }
    if (!indices.has(svg)) { indices.set(svg, vectors.length); vectors.push(svg); }
    names[name] = indices.get(svg);
  }
  const header = "// Generated by scripts/build-icons.cjs.\n(() => {\n'use strict';\nif (globalThis.SCIcons) return;\n";
  const output = header + 'const vectors = globalThis.customElements ? ' + JSON.stringify(vectors) + ' : null;\nconst names = ' + JSON.stringify(names) + ';\n' + runtime + '\n})();\n';
  // The isolated world has no registry: only helpers, never geometry or renderer.
  const helperStart = runtime.indexOf('  const escape ='), helperEnd = runtime.indexOf('  const resolve =');
  const apiStart = runtime.indexOf('  globalThis.SCIcons = Object.freeze('), apiEnd = runtime.lastIndexOf('\n}');
  if (helperStart < 0 || helperEnd < helperStart || apiStart < 0 || apiEnd < apiStart) throw new Error('Icon runtime helper boundaries changed');
  const client = header + 'const names = ' + JSON.stringify(names) + ';\n' + runtime.slice(helperStart, helperEnd) + runtime.slice(apiStart, apiEnd) + '\n})();\n';
  const cursor = catalog[aliases.slice].replace('<svg ', '<svg width="24" height="24" ').replace('fill="currentColor"', 'fill="white" stroke="#111" stroke-width="40" paint-order="stroke"');
  const cursorCss = '/* Generated by scripts/build-icons.cjs. */\n:root{--sc-cursor-slice:url("data:image/svg+xml,' + encodeURIComponent(cursor) + '") 12 12,crosshair}\n';
  return { output, client, cursorCss, names, vectorCount: vectors.length };
}

function build(directory = root, { check = false } = {}) {
  const read = file => fs.readFileSync(path.join(directory, file), 'utf8');
  const sources = packageFiles(directory)
    .filter(file => /\.(?:html|m?js)$/.test(file) && !/scripts\/(?:icons(?:-client)?\.js|vendor\/)/.test(file))
    .map(read);
  const result = compile({ sources, aliases: JSON.parse(read('scripts/icon-aliases.json')),
    catalog: JSON.parse(read('scripts/icon-vectors.json')), runtime: read('scripts/icons-runtime.js'),
    include: JSON.parse(read('scripts/icon-include.json')) });
  for (const [file, content] of [['scripts/icons.js', result.output], ['scripts/icons-client.js', result.client], ['assets/icon-cursors.css', result.cursorCss]]) {
    if (check) {
      if (!fs.existsSync(path.join(directory, file)) || read(file).replace(/\r\n/g, '\n') !== content.replace(/\r\n/g, '\n')) {
        throw new Error('Stale ' + file + '; run npm run build:icons before packaging.');
      }
    } else fs.writeFileSync(path.join(directory, file), content);
  }
  return result;
}

module.exports = { build, compile, selectNames, packageFiles };
if (require.main === module) {
  const result = build(root, { check: process.argv.includes('--check') });
  console.log('Icons: ' + result.vectorCount + ' vectors, ' + Object.keys(result.names).length + ' names; ' + Buffer.byteLength(result.output) + ' bytes renderer, ' + Buffer.byteLength(result.client) + ' bytes isolated helpers.');
}
