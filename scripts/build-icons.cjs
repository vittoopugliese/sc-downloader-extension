// Reproducible, offline compilation of the extracted vectors. No fonts or fetches at runtime.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, '.fl-studio-icons/manifest.json'), 'utf8'));
const aliases = JSON.parse(fs.readFileSync(path.join(__dirname, 'icon-aliases.json'), 'utf8'));
const vectors = {}, names = { ...aliases };
for (const [family, prefix] of [['ILGlyphsEx', 'glyph'], ['ILLogos', 'logo'], ['ILCursors', 'cursor']]) {
  for (const item of manifest[`font:${family}`].items) {
    const svg = fs.readFileSync(path.join(root, '.fl-studio-icons/glyph-fonts', family, item.file), 'utf8').trim();
    const key = `${prefix}:${item.codepoints[0].slice(2)}`;
    if (!/^<svg\b/.test(svg) || /<(?:script|image|foreignObject)\b|\bon\w+=|(?:href|url)\s*[=(]/i.test(svg)) throw new Error(`Unsafe vector: ${item.file}`);
    vectors[key] = svg;
    names[`${prefix}:${item.glyph}`] = key;
    for (const cp of item.codepoints) names[`${prefix}:${cp.slice(2)}`] = key;
  }
}
for (const [name, key] of Object.entries(aliases)) if (!vectors[key]) throw new Error(`Unknown icon ${name}: ${key}`);
const output = `// Generated by scripts/build-icons.cjs. Edit icon-aliases.json and icons-runtime.js instead.\n(() => {\n'use strict';\nif (globalThis.SCIcons) return;\nconst vectors = globalThis.customElements ? ${JSON.stringify(vectors)} : null;\nconst names = ${JSON.stringify(names)};\n${fs.readFileSync(path.join(__dirname, 'icons-runtime.js'), 'utf8')}\n})();\n`;
fs.writeFileSync(path.join(__dirname, 'icons.js'), output);
// Legacy asset paths stay compatible, but all app controls use <sc-icon>.
const legacy = { 'folder-icon': 'folder', cross: 'close', 'back-arrow': 'back', 'teleport-to-selected-track': 'locate', 'sound-cloud-social-badge': 'soundcloud', megaphone: 'sampler' };
for (const file of fs.readdirSync(path.join(root, 'assets/icons')).filter(file => file.endsWith('.svg'))) {
  const name = legacy[file.slice(0, -4)] || file.slice(0, -4);
  if (!aliases[name]) throw new Error(`Unmapped legacy icon: ${file}`);
  fs.writeFileSync(path.join(root, 'assets/icons', file), vectors[aliases[name]] + '\n');
}
// CSS cursor graphics must be URLs. Generate the URL here from the same named icon.
const cursor = vectors[aliases.slice].replace('<svg ', '<svg width="24" height="24" ').replace('fill="currentColor"', 'fill="white" stroke="#111" stroke-width="40" paint-order="stroke"');
fs.writeFileSync(path.join(root, 'assets/icon-cursors.css'), `/* Generated by scripts/build-icons.cjs. */\n:root{--sc-cursor-slice:url("data:image/svg+xml,${encodeURIComponent(cursor)}") 12 12,crosshair}\n`);
console.log(`${Object.keys(vectors).length} vectors, ${Object.keys(aliases).length} semantic names; ${Buffer.byteLength(output)} bytes, no external runtime assets.`);
